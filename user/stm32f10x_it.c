/**
  * @brief  This function handles Hard Fault exception.
  * @param  None
  * @retval None
  */
void HardFault_Handler(void)
{
    // ★ 关闭中断
    __disable_irq();
    
     // ★ 读取 MSP 和 PSP
    uint32_t msp = __get_MSP();
    uint32_t psp = __get_PSP();
    
    // ★ 判断是哪个栈（读 CONTROL 寄存器）
    uint32_t control = __get_CONTROL();
    uint32_t *stack;
    
    if (control & 0x02) {
        stack = (uint32_t*)psp;  // 使用 PSP
    } else {
        stack = (uint32_t*)msp;  // 使用 MSP
    }
    
    fault_pc = stack[6];  // PC
    fault_lr = stack[5];  // LR
    
    // ★ LED 快闪（正点原子精英板 LED0 = PB5，低电平点亮）
    while (1) {
        GPIO_ResetBits(GPIOB, GPIO_Pin_5);   // LED 亮
        for (volatile uint32_t i = 0; i < 500000; i++);
        GPIO_SetBits(GPIOB, GPIO_Pin_5);     // LED 灭
        for (volatile uint32_t i = 0; i < 500000; i++);
    }
}

